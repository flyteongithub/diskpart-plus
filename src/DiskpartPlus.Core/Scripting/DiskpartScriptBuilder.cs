using System.Globalization;
using DiskpartPlus.Core.Models;
using DiskpartPlus.Core.Operations;

namespace DiskpartPlus.Core.Scripting;

/// <summary>
/// Turns operations into diskpart commands. This is the only place in the app that
/// writes diskpart syntax, so if a command ever needs fixing, it gets fixed here.
/// </summary>
/// <remarks>
/// Every operation selects its own disk and partition, even if the one before it already did.
/// It costs a line or two but means no operation can quietly act on whatever was selected last.
/// We never use "noerr", so diskpart stops at the first thing that goes wrong.
/// </remarks>
public static class DiskpartScriptBuilder
{
    public const string Header = "rem Generated by Diskpart+";

    public static DiskpartScript Build(IEnumerable<DiskOperation> operations)
    {
        ArgumentNullException.ThrowIfNull(operations);

        var lines = new List<string> { Header };
        foreach (var operation in operations)
        {
            lines.Add("rem " + OneLine(operation.Describe()));
            lines.AddRange(CommandsFor(operation));
        }

        return new DiskpartScript(lines);
    }

    public static IReadOnlyList<string> CommandsFor(DiskOperation operation)
    {
        ArgumentNullException.ThrowIfNull(operation);
        var lines = new List<string>();

        switch (operation)
        {
            case CleanDisk clean:
                lines.Add(SelectDisk(clean.DiskNumber));
                lines.Add(clean.ZeroEverySector ? "clean all" : "clean");
                break;

            case ConvertPartitionStyle convert:
                lines.Add(SelectDisk(convert.DiskNumber));
                lines.Add(ConvertCommand(convert.To));
                break;

            case SetDiskOnline online:
                lines.Add(SelectDisk(online.DiskNumber));
                lines.Add(online.Online ? "online disk" : "offline disk");
                break;

            case SetDiskReadOnly readOnly:
                lines.Add(SelectDisk(readOnly.DiskNumber));
                lines.Add(readOnly.ReadOnly ? "attributes disk set readonly" : "attributes disk clear readonly");
                break;

            case SetDiskUniqueId uniqueId:
                lines.Add(SelectDisk(uniqueId.DiskNumber));
                lines.Add("uniqueid disk id=" + Plain(uniqueId.Id, "disk ID"));
                break;

            case CreatePartition create:
                lines.Add(SelectDisk(create.DiskNumber));
                lines.Add(CreatePartitionCommand(create.Kind, create.Size));

                // diskpart leaves the new partition selected, so these act on it.
                if (create.Format is not null)
                {
                    lines.Add(FormatCommand(create.Format, forceDismount: false));
                }

                if (create.Assign is not null)
                {
                    lines.Add(AssignCommand(create.Assign.Letter));
                }

                break;

            case FormatPartition format:
                lines.AddRange(SelectPartition(format));
                lines.Add(FormatCommand(format.Format, forceDismount: true));
                break;

            case DeletePartition delete:
                lines.AddRange(SelectPartition(delete));
                lines.Add(delete.Override ? "delete partition override" : "delete partition");
                break;

            case ExtendPartition extend:
                lines.AddRange(SelectPartition(extend));
                lines.Add(extend.By is { } by ? Inv($"extend size={RequireWholeMegabytes(by)}") : "extend");
                break;

            case ShrinkPartition shrink:
                lines.AddRange(SelectPartition(shrink));

                // Giving the same number for both means it shrinks by exactly that much or fails,
                // instead of quietly shrinking by less.
                var megabytes = RequireWholeMegabytes(shrink.By);
                lines.Add(Inv($"shrink desired={megabytes} minimum={megabytes}"));
                break;

            case AssignDriveLetter assign:
                lines.AddRange(SelectPartition(assign));
                if (assign.Replacing is { } old)
                {
                    lines.Add($"remove letter={old}");
                }

                lines.Add(AssignCommand(assign.Letter));
                break;

            case RemoveDriveLetter remove:
                lines.AddRange(SelectPartition(remove));
                lines.Add($"remove letter={remove.Letter}");
                break;

            case SetPartitionType setType:
                lines.AddRange(SelectPartition(setType));

                // The planner checks the type fits the disk. Here we just need one of the two IDs.
                var id = setType.Type.GptId?.ToString("D")
                    ?? setType.Type.MbrId?.ToString("X2", CultureInfo.InvariantCulture)
                    ?? throw new ArgumentException("The partition type has no ID to set.", nameof(operation));
                lines.Add($"set id={id} override");
                break;

            case SetGptAttributes attributes:
                lines.AddRange(SelectPartition(attributes));
                lines.Add(Inv($"gpt attributes=0x{(ulong)attributes.Attributes:X16}"));
                break;

            case CreateVirtualDisk create:
                var type = create.Allocation == VirtualDiskAllocation.Fixed ? "fixed" : "expandable";
                lines.Add(Inv($"create vdisk file={QuotePath(create.FilePath)} maximum={RequireWholeMegabytes(create.MaximumSize)} type={type}"));

                if (create.Attach || create.Setup is not null)
                {
                    lines.Add($"select vdisk file={QuotePath(create.FilePath)}");
                    lines.Add("attach vdisk");
                }

                // Once attached, the new disk has focus, so we can set it up straight away.
                if (create.Setup is not null)
                {
                    lines.Add(ConvertCommand(create.Setup.Style));
                    lines.Add(CreatePartitionCommand(NewPartitionKind.Primary, size: null));
                    lines.Add(FormatCommand(create.Setup.Format, forceDismount: false));
                    if (create.Setup.Assign is not null)
                    {
                        lines.Add(AssignCommand(create.Setup.Assign.Letter));
                    }
                }

                break;

            case AttachVirtualDisk attach:
                lines.Add($"select vdisk file={QuotePath(attach.FilePath)}");
                lines.Add(attach.ReadOnly ? "attach vdisk readonly" : "attach vdisk");
                break;

            case DetachVirtualDisk detach:
                lines.Add($"select vdisk file={QuotePath(detach.FilePath)}");
                lines.Add("detach vdisk");
                break;

            default:
                throw new NotSupportedException($"Don't know how to script {operation.GetType().Name}.");
        }

        return lines;
    }

    private static string SelectDisk(int diskNumber)
    {
        ArgumentOutOfRangeException.ThrowIfNegative(diskNumber);
        return Inv($"select disk {diskNumber}");
    }

    private static IEnumerable<string> SelectPartition(PartitionScopedOperation operation)
    {
        ArgumentOutOfRangeException.ThrowIfLessThan(operation.PartitionNumber, 1);
        yield return SelectDisk(operation.DiskNumber);
        yield return Inv($"select partition {operation.PartitionNumber}");
    }

    private static string ConvertCommand(PartitionStyle style) => style switch
    {
        PartitionStyle.Gpt => "convert gpt",
        PartitionStyle.Mbr => "convert mbr",
        _ => throw new ArgumentOutOfRangeException(nameof(style), style, "A disk can only be converted to GPT or MBR."),
    };

    private static string CreatePartitionCommand(NewPartitionKind kind, ByteSize? size)
    {
        var command = kind switch
        {
            NewPartitionKind.Efi => "create partition efi",
            NewPartitionKind.MicrosoftReserved => "create partition msr",
            _ => "create partition primary",
        };

        return size is { } s ? Inv($"{command} size={RequireWholeMegabytes(s)}") : command;
    }

    private static string FormatCommand(FormatSpec format, bool forceDismount)
    {
        var parts = new List<string> { "format", "fs=" + format.FileSystem.DiskpartName() };

        if (!string.IsNullOrEmpty(format.Label))
        {
            parts.Add("label=" + Quote(format.Label, "label"));
        }

        if (format.AllocationUnitBytes is { } unit)
        {
            ArgumentOutOfRangeException.ThrowIfNegativeOrZero(unit);
            parts.Add(Inv($"unit={unit}"));
        }

        if (format.Quick)
        {
            parts.Add("quick");
        }

        // On an existing volume, "override" lets diskpart dismount it first if something has it open.
        if (forceDismount)
        {
            parts.Add("override");
        }

        return string.Join(' ', parts);
    }

    private static string AssignCommand(DriveLetter? letter) =>
        letter is { } l ? $"assign letter={l}" : "assign";

    private static long RequireWholeMegabytes(ByteSize size)
    {
        var megabytes = size.WholeMegabytes;
        if (megabytes < 1)
        {
            throw new ArgumentOutOfRangeException(nameof(size), size, "diskpart sizes have to be at least 1 MB.");
        }

        return megabytes;
    }

    // Anything we put in quotes must not be able to close the quotes or start a new line,
    // otherwise a label could sneak an extra command into the script.
    private static string Quote(string value, string what)
    {
        if (value.Any(c => c == '"' || char.IsControl(c)))
        {
            throw new ArgumentException($"The {what} can't contain quotes or control characters.", nameof(value));
        }

        return "\"" + value + "\"";
    }

    private static string QuotePath(string path)
    {
        if (string.IsNullOrWhiteSpace(path))
        {
            throw new ArgumentException("The file path is empty.", nameof(path));
        }

        return Quote(path, "file path");
    }

    // For unquoted values like IDs. Letters, digits, dashes and braces only.
    private static string Plain(string value, string what)
    {
        if (string.IsNullOrWhiteSpace(value) || !value.All(c => char.IsAsciiLetterOrDigit(c) || c is '-' or '{' or '}'))
        {
            throw new ArgumentException($"The {what} \"{value}\" has characters diskpart won't accept.", nameof(value));
        }

        return value;
    }

    private static string OneLine(string text)
    {
        var cleaned = new string(text.Select(c => char.IsControl(c) ? ' ' : c).ToArray()).Trim();
        return cleaned.Length == 0 ? "-" : cleaned;
    }

    private static string Inv(FormattableString text) => FormattableString.Invariant(text);
}
